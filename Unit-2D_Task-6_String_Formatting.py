name = "John"
age = 20
marks = 85.5

# Using format()
print("Using format(): Name: {}, Age: {}, Marks: {}".format(name, age, marks))

# Using f-strings
print(f"Using f-string: Name: {name}, Age: {age}, Marks: {marks}")

# Using % operator
print("Using % operator: Name: %s, Age: %d, Marks: %.1f" % (name, age, marks))